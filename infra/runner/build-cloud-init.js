#!/usr/bin/env node
/**
 * Builds oracle-cloud-init.sh: one script to paste into Oracle Cloud's
 * "Create compute instance" form, with server.js and setup.sh inside it, so
 * the runner sets itself up at first boot with no SSH. Run after changing
 * either file:  node infra/runner/build-cloud-init.js
 * A test fails if the committed script is out of date.
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

/** Oracle limits instance user data to 32,000 bytes. */
const MAX_BYTES = 32000

function buildCloudInit(dir = __dirname) {
  const server = fs.readFileSync(path.join(dir, 'server.js'), 'utf8').replace(/\r\n/g, '\n')
  const setup = fs.readFileSync(path.join(dir, 'setup.sh'), 'utf8').replace(/\r\n/g, '\n')
  for (const [name, text] of [
    ['server.js', server],
    ['setup.sh', setup],
  ]) {
    if (text.includes('NEXUS_RUNNER_EOF')) throw new Error(`${name} contains the heredoc marker`)
  }
  const script = `#!/bin/bash
# Nexus runner, set up at first boot. Paste this whole file into Oracle
# Cloud's "Create compute instance" form: Show advanced options >
# Management > Paste cloud-init script. Fill in the two lines below first.
# (Generated by infra/runner/build-cloud-init.js; edit the sources, not this.)

# 1. The runner's web address, e.g. yourname.duckdns.org
RUNNER_DOMAIN="CHANGE-ME.duckdns.org"

# 2. A long random password, 40 or more letters and digits, that only you
#    and Vercel will know. Paste the same value into Vercel as
#    JUDGE0_AUTH_TOKEN. (Left as CHANGE-ME, one is generated; read it later
#    over SSH with: sudo cat /root/nexus-runner.txt)
RUNNER_TOKEN="CHANGE-ME"

set -euo pipefail
SRC=/opt/nexus-runner-src
mkdir -p "$SRC"

cat > "$SRC/server.js" <<'NEXUS_RUNNER_EOF'
${server.trimEnd()}
NEXUS_RUNNER_EOF

cat > "$SRC/setup.sh" <<'NEXUS_RUNNER_EOF'
${setup.trimEnd()}
NEXUS_RUNNER_EOF

case "$RUNNER_DOMAIN" in
  *CHANGE-ME*)
    echo "Set RUNNER_DOMAIN at the top of the cloud-init script, then recreate the instance." >&2
    exit 1
    ;;
esac
if [ "$RUNNER_TOKEN" = "CHANGE-ME" ]; then
  RUNNER_TOKEN=""
fi
RUNNER_TOKEN="$RUNNER_TOKEN" bash "$SRC/setup.sh" "$RUNNER_DOMAIN"
`
  if (Buffer.byteLength(script) > MAX_BYTES) {
    throw new Error(
      `cloud-init script is ${Buffer.byteLength(script)} bytes; Oracle allows ${MAX_BYTES}`
    )
  }
  return script
}

if (require.main === module) {
  const target = path.join(__dirname, 'oracle-cloud-init.sh')
  fs.writeFileSync(target, buildCloudInit())
  console.log(`Wrote ${path.relative(process.cwd(), target)}`)
}

module.exports = { buildCloudInit, MAX_BYTES }
